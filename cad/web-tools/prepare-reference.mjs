import fs from 'node:fs';
import {NodeIO} from '@gltf-transform/core';
import {ALL_EXTENSIONS} from '@gltf-transform/extensions';
import {weld,simplify,dedup,draco,prune} from '@gltf-transform/functions';
import draco3d from 'draco3dgltf';
import {MeshoptSimplifier} from 'meshoptimizer';
await MeshoptSimplifier.ready;
const io=new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({'draco3d.encoder':await draco3d.createEncoderModule(),'draco3d.decoder':await draco3d.createDecoderModule()});
const root=new URL('../../../public/cad/', import.meta.url).pathname;
const doc=await io.read(root+'reference-v3.glb');
const count=()=>doc.getRoot().listMeshes().reduce((a,m)=>a+m.listPrimitives().reduce((n,p)=>n+p.getIndices().getCount()/3,0),0);
const before=count();
await doc.transform(weld(),simplify({simplifier:MeshoptSimplifier,ratio:.4,error:.0003,lockBorder:true}),dedup(),prune({keepLeaves:true}));
const after=count();
await doc.transform(draco({method:'edgebreaker',quantizePosition:18,quantizeNormal:12,quantizationVolume:'mesh'}));
await io.write(root+'reference-v3-web.glb',doc);
const decoded=await io.read(root+'reference-v3-web.glb');
for(const ext of decoded.getRoot().listExtensionsUsed())if(ext.extensionName==='KHR_draco_mesh_compression')ext.dispose();
fs.mkdirSync(new URL('../../../work/', import.meta.url),{recursive:true});
await io.write(new URL('../../../work/reference-v3-decoded.glb',import.meta.url).pathname,decoded);
const {createHash}=await import('node:crypto');
const bytes=fs.readFileSync(root+'reference-v3-web.glb');
const report={source:'reference-v3.glb',sourceSha256:createHash('sha256').update(fs.readFileSync(root+'reference-v3.glb')).digest('hex'),asset:'reference-v3-web.glb',sha256:createHash('sha256').update(bytes).digest('hex'),sourceTriangles:before,webTriangles:after,bytes:bytes.length,verifiedOemReplica:false};
fs.writeFileSync(root+'reference-v3-web.json',JSON.stringify(report,null,2)+'\n');
console.log(report);
